import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PLUGIN_FILE_NAME = 'evolver.js';
const PLUGIN_HEADER = '// _evolver_managed: true (do not remove this line)';
const LEGACY_AGENTS_MARKER = '<!-- evolver-opencode-evolution-memory -->';
const LEGACY_AGENTS_END_MARKER = '<!-- /evolver-opencode-evolution-memory -->';
const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVER_ENTRY = path.join(PACKAGE_ROOT, 'src', 'server.js');
export const TUI_ENTRY = path.join(PACKAGE_ROOT, 'src', 'tui.js');

function usage() {
  return `Usage: evolver-opencode-plugin [--install|--verify|--uninstall] [--config-root <dir>] [--force]

Installs the local-file OpenCode plugin into <config-root>/.opencode: the server plugin in plugins/ and the
TUI plugin (the /evolver-* commands) in tui.json. For npm installs run \`opencode plugin evolver-opencode-plugin\`
instead; no CLI install step is required.
`;
}

export function parseArgs(argv) {
  const args = { action: 'install', configRoot: process.cwd(), force: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--install') args.action = 'install';
    else if (arg === '--verify') args.action = 'verify';
    else if (arg === '--uninstall') args.action = 'uninstall';
    else if (arg === '--force') args.force = true;
    else if (arg === '--help' || arg === '-h') args.action = 'help';
    else if (arg === '--config-root') {
      i += 1;
      args.configRoot = argv[i] || args.configRoot;
    } else if (arg.startsWith('--config-root=')) {
      args.configRoot = arg.slice('--config-root='.length);
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  args.configRoot = path.resolve(args.configRoot);
  return args;
}

export function pluginSource() {
  return `${PLUGIN_HEADER}
// Auto-generated by evolver-opencode-plugin: delegates to the package's server plugin.

export { default } from ${JSON.stringify(pathToFileURL(SERVER_ENTRY).href)};
`;
}

export function paths(configRoot) {
  const opencodeDir = path.join(configRoot, '.opencode');
  return {
    pluginPath: path.join(opencodeDir, 'plugins', PLUGIN_FILE_NAME),
    tuiConfigPath: path.join(opencodeDir, 'tui.json'),
    agentsMdPath: path.join(configRoot, 'AGENTS.md'),
  };
}

export function isManaged(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8').includes('_evolver_managed: true');
  } catch {
    return false;
  }
}

function atomicWrite(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const tmp = path.join(path.dirname(filePath), `.${path.basename(filePath)}.${process.pid}.tmp`);
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, filePath);
}

function readJson(filePath) {
  try {
    return { value: JSON.parse(fs.readFileSync(filePath, 'utf8')) };
  } catch (error) {
    return error?.code === 'ENOENT' ? { value: {} } : { error };
  }
}

function tuiPlugins(config) {
  return Array.isArray(config.plugin) ? config.plugin : [];
}

const isTuiEntry = (spec) => (Array.isArray(spec) ? spec[0] : spec) === TUI_ENTRY;

function addTuiPlugin(filePath) {
  const { value, error } = readJson(filePath);
  if (error) return `not changed: ${filePath} is not plain JSON; add "${TUI_ENTRY}" to its "plugin" list`;
  if (tuiPlugins(value).some(isTuiEntry)) return null;
  atomicWrite(filePath, `${JSON.stringify({ ...value, plugin: [...tuiPlugins(value), TUI_ENTRY] }, null, 2)}\n`);
  return null;
}

function removeTuiPlugin(filePath) {
  const { value, error } = readJson(filePath);
  if (error || !tuiPlugins(value).some(isTuiEntry)) return false;
  atomicWrite(filePath, `${JSON.stringify({ ...value, plugin: tuiPlugins(value).filter((spec) => !isTuiEntry(spec)) }, null, 2)}\n`);
  return true;
}

// Installs before 0.2.0 wrote an Evolver section into AGENTS.md, which OpenCode puts in every prompt.
export function removeLegacyAgentsSection(filePath) {
  let content;
  try {
    content = fs.readFileSync(filePath, 'utf8');
  } catch {
    return false;
  }
  const start = content.indexOf(LEGACY_AGENTS_MARKER);
  if (start === -1) return false;
  const endMarker = content.indexOf(LEGACY_AGENTS_END_MARKER, start);
  let end = content.length;
  if (endMarker !== -1) {
    const lineBreak = content.indexOf('\n', endMarker + LEGACY_AGENTS_END_MARKER.length);
    end = lineBreak === -1 ? content.length : lineBreak + 1;
  }
  atomicWrite(filePath, `${(content.slice(0, start).trimEnd() + content.slice(end)).trimEnd()}\n`);
  return true;
}

export function install({ configRoot, force }) {
  const p = paths(configRoot);
  if (fs.existsSync(p.pluginPath) && !isManaged(p.pluginPath) && !force) {
    return { ok: false, action: 'install', error: `refusing to overwrite user-owned plugin: ${p.pluginPath}` };
  }
  atomicWrite(p.pluginPath, pluginSource());
  const tuiWarning = addTuiPlugin(p.tuiConfigPath);
  removeLegacyAgentsSection(p.agentsMdPath);
  return { ok: true, action: 'install', plugin_path: p.pluginPath, tui_config_path: p.tuiConfigPath, warning: tuiWarning, config_root: configRoot };
}

async function loadsAsPlugin(filePath) {
  try {
    const mod = await import(`${pathToFileURL(filePath).href}?verify=${Date.now()}`);
    return typeof mod.default?.server === 'function' ? null : 'default export has no server()';
  } catch (error) {
    return error?.message || String(error);
  }
}

function hasLegacyAgentsSection(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8').includes(LEGACY_AGENTS_MARKER);
  } catch {
    return false;
  }
}

export async function verify({ configRoot }) {
  const p = paths(configRoot);
  const pluginExists = fs.existsSync(p.pluginPath);
  const loadError = pluginExists ? await loadsAsPlugin(p.pluginPath) : 'plugin file is absent';
  const tuiListed = tuiPlugins(readJson(p.tuiConfigPath).value ?? {}).some(isTuiEntry);
  const legacy = hasLegacyAgentsSection(p.agentsMdPath);
  const checks = [
    { id: 'plugin_file_present', ok: pluginExists, detail: pluginExists ? p.pluginPath : `missing: ${p.pluginPath}` },
    { id: 'plugin_managed_marker', ok: pluginExists && isManaged(p.pluginPath), detail: 'contains _evolver_managed: true' },
    { id: 'plugin_loadable', ok: loadError === null, detail: loadError === null ? 'default export is { id, server }' : `import failed: ${loadError}` },
    { id: 'tui_plugin_listed', ok: tuiListed, detail: tuiListed ? `${p.tuiConfigPath} lists ${TUI_ENTRY}` : `${p.tuiConfigPath} does not list ${TUI_ENTRY}` },
    { id: 'no_agents_md_section', ok: !legacy, detail: legacy ? 'AGENTS.md still holds the pre-0.2.0 Evolver section' : 'AGENTS.md holds nothing of Evolver' },
  ];
  return { ok: checks.every((check) => check.ok), action: 'verify', plugin_path: p.pluginPath, config_root: configRoot, checks };
}

export function uninstall({ configRoot }) {
  const p = paths(configRoot);
  let removed = false;
  if (isManaged(p.pluginPath)) {
    fs.unlinkSync(p.pluginPath);
    removed = true;
  }
  if (removeTuiPlugin(p.tuiConfigPath)) removed = true;
  if (removeLegacyAgentsSection(p.agentsMdPath)) removed = true;
  return { ok: true, action: 'uninstall', removed, plugin_path: p.pluginPath, config_root: configRoot };
}

function printReport(report) {
  if (report.action === 'verify') {
    console.log(`[opencode] Verify ${report.ok ? 'passed' : 'failed'}`);
    console.log(`[opencode]   plugin path : ${report.plugin_path}`);
    console.log(`[opencode]   config root : ${report.config_root}`);
    for (const check of report.checks) console.log(`[opencode]   ${check.ok ? '[OK]  ' : '[FAIL]'} ${check.id} -- ${check.detail}`);
    return;
  }
  if (!report.ok) {
    console.error(`[opencode] ${report.error || 'operation failed'}`);
    return;
  }
  console.log(`[opencode] ${report.action === 'uninstall' ? 'Uninstalled' : 'Installed'} Evolver plugin at ${report.plugin_path}`);
  if (report.warning) console.log(`[opencode] TUI commands ${report.warning}`);
  if (report.action === 'install') console.log('[opencode] Restart OpenCode for the plugin to take effect.');
}

async function main() {
  let args;
  try {
    args = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(error?.message || String(error));
    console.error(usage());
    process.exit(2);
  }
  if (args.action === 'help') {
    process.stdout.write(usage());
    return;
  }
  const actions = { install, verify, uninstall };
  const report = await actions[args.action](args);
  printReport(report);
  if (!report.ok) process.exit(1);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
